export function preloadArt(s:Phaser.Scene){for(const [path,url] of Object.entries(images)){const key=path.split('/').pop()!.replace('.png','');if(key==='gruk'||key.startsWith('gruk-'))s.load.spritesheet(key,url,{frameWidth:48,frameHeight:56});else if(key.endsWith("-anim"))s.load.spritesheet(key,url,{frameWidth:48,frameHeight:48});else s.load.image(key,url);}}
export function createArt(s:Phaser.Scene){for(const kind of ["chop","pickaxe","gather","harvest","bucket"])for(let r=0;r<4;r++){const key=`gruk-${kind}-${r}`;if(!s.anims.exists(key)&&s.textures.exists(`gruk-${kind}`)){const frames=s.anims.generateFrameNumbers(`gruk-${kind}`,{start:r*6,end:r*6+5});if(frames.length===6)s.anims.create({key,frames,repeat:0,frameRate:12});}}for(const kind of ["rabbit","goblin","bandit"]){for(const [name,start,repeat] of [["walk",0,-1],["attack",4,0]] as const){const key=kind+"-"+name;if(!s.anims.exists(key))s.anims.create({key,frames:s.anims.generateFrameNumbers(kind+"-anim",{start,end:start+3}),repeat,frameRate:10});}}for(let r=0;r<4;r++){for(const [name,offset,repeat,frameRate] of [['walk',0,-1,9],['swing',4,0,12]] as const){const key=`gruk-${name}-${r}`;if(!s.anims.exists(key))s.anims.create({key,frames:s.anims.generateFrameNumbers('gruk',{start:r*8+offset,end:r*8+offset+3}),repeat,frameRate});}}}
